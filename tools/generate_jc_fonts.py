#!/usr/bin/env python3
"""Generate fixed-size 4-bit anti-aliased glyphs for the JC pendant."""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / "assets" / "fonts"
OUTPUT = ROOT / "src" / "jc8048w550" / "JcFonts.generated.hpp"
CHARACTERS = list(range(32, 127)) + [176]


def load_font(path: Path, size: int, weight: int, width: int | None = None):
    font = ImageFont.truetype(str(path), size)
    if width is None:
        font.set_variation_by_axes([weight])
    else:
        font.set_variation_by_axes([weight, width])
    return font


def rasterize(name: str, font: ImageFont.FreeTypeFont) -> tuple[str, int, int]:
    ascent, descent = font.getmetrics()
    bitmap = bytearray()
    glyphs = []
    for codepoint in CHARACTERS:
        character = chr(codepoint)
        left, top, right, bottom = font.getbbox(character, anchor="ls")
        width = max(0, right - left)
        height = max(0, bottom - top)
        image = Image.new("L", (max(1, width), max(1, height)), 0)
        if width and height:
            ImageDraw.Draw(image).text(
                (-left, -top), character, font=font, fill=255, anchor="ls"
            )
        pixels = [round(pixel * 15 / 255) for pixel in image.tobytes()]
        if len(bitmap) & 1:
            bitmap.append(0)
        offset = len(bitmap)
        for index in range(0, len(pixels), 2):
            high = pixels[index]
            low = pixels[index + 1] if index + 1 < len(pixels) else 0
            bitmap.append((high << 4) | low)
        advance = round(font.getlength(character))
        if not (0 <= advance <= 255 and width <= 255 and height <= 255):
            raise ValueError(f"Glyph metrics exceed the generated format: {name} {character!r}")
        glyphs.append((offset, advance, left, top, width, height))

    if len(bitmap) > 65535:
        raise ValueError(f"Font data exceeds 16-bit offsets: {name}")

    rows = [
        f"static const Glyph {name}Glyphs[] PROGMEM = {{",
    ]
    rows.extend(
        "    {%d, %d, %d, %d, %d, %d},"
        % (offset, advance, left, top, width, height)
        for offset, advance, left, top, width, height in glyphs
    )
    rows.append("};")
    rows.append(f"static const uint8_t {name}Bitmap[] PROGMEM = {{")
    for start in range(0, len(bitmap), 16):
        rows.append("    " + ", ".join(f"0x{value:02X}" for value in bitmap[start:start + 16]) + ",")
    rows.append("};")
    rows.append(
        f"static const Font {name} = {{{name}Glyphs, {name}Bitmap, "
        f"{ascent + descent}, {ascent}}};"
    )
    return "\n".join(rows), len(bitmap), ascent + descent


def main() -> None:
    declarations = []
    total_bitmap_bytes = 0
    fonts = [
        ("kRoboto16", load_font(FONT_DIR / "Roboto-Variable.ttf", 16, 400, 100)),
        ("kRoboto20", load_font(FONT_DIR / "Roboto-Variable.ttf", 20, 500, 100)),
        ("kRoboto24", load_font(FONT_DIR / "Roboto-Variable.ttf", 24, 600, 100)),
    ]
    fonts.extend(
        (f"kRobotoMono{size}", load_font(FONT_DIR / "RobotoMono-Variable.ttf", size, 400))
        for size in (18, 20, 22, 24, 26, 28, 30, 32)
    )
    for name, font in fonts:
        declaration, byte_count, _ = rasterize(name, font)
        declarations.append(declaration)
        total_bitmap_bytes += byte_count

    header = """// Generated by tools/generate_jc_fonts.py; do not edit.
#pragma once

#include <Arduino.h>

namespace jc8048w550 {
namespace fonts {

struct Glyph {
    uint16_t offset;
    uint8_t advance;
    int8_t x_offset;
    int8_t y_offset;
    uint8_t width;
    uint8_t height;
};

struct Font {
    const Glyph* glyphs;
    const uint8_t* bitmap;
    uint8_t line_height;
    uint8_t baseline;
};

// Character slots are ASCII 32..126 followed by U+00B0 (degree).
"""
    header += "\n\n".join(declarations)
    header += "\n\n} // namespace fonts\n} // namespace jc8048w550\n"
    OUTPUT.write_text(header, encoding="utf-8")
    print(f"Generated {OUTPUT.relative_to(ROOT)}: {total_bitmap_bytes} bitmap bytes, "
          f"{len(fonts)} raster sizes")


if __name__ == "__main__":
    main()
